SET search_path TO gs_gss, public;

CREATE TABLE users (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username                   VARCHAR(16)  NOT NULL UNIQUE,
    email                      VARCHAR(255),
    password                   VARCHAR(255),
    nickname                   VARCHAR(50)  NOT NULL,
    user_type                  VARCHAR(50)  NOT NULL,
    agent_code                 VARCHAR(4),
    parent_id                  BIGINT, -- FK → users(id)
    last_modified_by           BIGINT,
    protected                  BOOLEAN      NOT NULL DEFAULT false,
    status                     VARCHAR(50)  NOT NULL DEFAULT 'active',
    last_login_time            TIMESTAMPTZ,
    last_login_ip              VARCHAR(45),
    created_time               TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_time               TIMESTAMPTZ,
    version                    INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT users_user_type_chk CHECK (user_type IN ('studio', 'master_agent', 'sub_account'))
);

CREATE UNIQUE INDEX users_agent_code_key
    ON users (agent_code)
    WHERE user_type = 'master_agent' AND agent_code IS NOT NULL;

CREATE INDEX users_parent_id_idx ON users (parent_id);
CREATE INDEX users_user_type_idx ON users (user_type);
CREATE INDEX users_last_login_idx ON users (last_login_time);
CREATE INDEX users_list_idx ON users (user_type, parent_id, last_login_time DESC);
