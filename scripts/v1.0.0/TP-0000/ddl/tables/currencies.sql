-- Option B: currency_type on currencies; currency_code_id nullable for custom_point
SET search_path TO gs_gss, public;

CREATE TABLE IF NOT EXISTS currencies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_code_id BIGINT       UNIQUE, -- FK → currency_codes(id); NULL for custom_point
    code             VARCHAR(10)  NOT NULL, -- 幣別代碼（USD01、PT001）
    name             VARCHAR(20)  NOT NULL, -- 幣別名稱
    currency_type    VARCHAR(20)  NOT NULL, -- fiat | crypto | custom_point
    active           BOOLEAN      NOT NULL DEFAULT true,
    bet_options      JSONB        NOT NULL, -- 10 bet values ASC; app validates
    created_by       BIGINT,
    created_time     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_time     TIMESTAMPTZ,
    version          INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT currencies_currency_type_chk CHECK (currency_type IN ('fiat', 'crypto', 'custom_point')),
    CONSTRAINT currencies_type_fk_chk CHECK (
        (currency_type IN ('fiat', 'crypto') AND currency_code_id IS NOT NULL)
        OR (currency_type = 'custom_point' AND currency_code_id IS NULL)
    ),
    CONSTRAINT idx_c_c UNIQUE (code),
    CONSTRAINT idx_c_cci UNIQUE (currency_code_id)
);

CREATE INDEX IF NOT EXISTS idx_c_n ON currencies (name);
CREATE INDEX IF NOT EXISTS idx_c_ct ON currencies (currency_type);
